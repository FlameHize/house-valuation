# ============================================================
# DCF
# ============================================================
st.subheader("二、DCF 现金流估值模型")

with st.expander("📘 模型原理", expanded=True):
    st.markdown("""
    DCF（Discounted Cash Flow，现金流贴现）是金融领域最基础的资产估值方法。核心思想是：

    > **一项资产的价值，等于它未来能为你节省或产生的所有现金流的现值之和。**

    在房产场景中，买房相当于：
    - **节省了未来的租金支出**（如果不买房，你需要一直付房租）
    - **付出了月供和持有成本**（物业费、维修费等）
    - **持有期满后获得残值**（卖房回收的资金）

    把这三部分现金流按一定折现率折算到今天，就是这套房子的**居住公允价值**。
    """)

with st.expander("📐 核心公式"):
    st.markdown("#### 居住公允价值（实际值框架）")
    st.latex(r"""
    \text{FairValue} = \sum_{t=1}^{n} \frac{Rent_t - Cost_t}{(1 + r)^t} + TV
    """)
    st.markdown("""
    其中：
    - **Rentₜ** = 第 t 年的租金节省 = 月租金 × 12 × (1 + g)ᵗ
    - **Costₜ** = 第 t 年的持有成本 = 年物业费维修费 × (1 + g)ᵗ
    - **TV** = 期末残值（Terminal Value），已通过折旧和人口比例折算为当期人民币
    - **r** = 实际折现率
    - **g** = 租金/成本实际增长率
    - **n** = 持有期（年）

    > 期末残值采用两段式折算法，**不再额外折现**：
    > TV = P₀ × (1 - d)ⁿ × R_pop
    >
    > - d = 年折旧率（物理老化）
    > - R_pop = 终值人口比例
    >
    > 这两项已将未来残值换算为当期购买力，若再用 (1+r)ⁿ 折现会重复计算。
    """)

    st.markdown("#### 期末残值（两段式模型）")
    st.latex(r"""
    TV = P_0 \times (1 - d)^n \times R_{pop}
    """)
    st.markdown("""
    其中：
    - **P₀** = 当前房屋总价
    - **d** = 年折旧率（物理老化）
    - **R_pop** = 终值人口比例（反映人口减少对房产需求的长期影响）
    """)

    st.markdown("#### 净现值 (NPV)")
    st.latex(r"""
    NPV = -DownPayment - Fees + \sum_{t=1}^{n} \frac{Rent_t - Loan_t - Cost_t}{(1 + r)^t} + TV
    """)
    st.markdown("""
    NPV > 0 → 买房比租房划算
    NPV < 0 → 租房并将资金用于理财更划算

    #### 等额本息月供
    """)
    st.latex(r"""
    M = P \times \frac{i(1 + i)^N}{(1 + i)^N - 1}
    """)
    st.markdown("""
    - **M** = 月供
    - **P** = 贷款本金
    - **i** = 月利率（年利率 ÷ 12）
    - **N** = 总期数（贷款年限 × 12）
    """)

with st.expander("📊 参数取值依据"):
    st.markdown("""
    | 参数 | 默认值 | 依据 |
    |------|--------|------|
    | 实际折现率 | 4.0% | 参考中国长期国债收益率（~2.5%）+ 房产流动性风险溢价（~1.5%） |
    | 租金/成本增长率 | 1.5% | 参考长期通胀水平及租金增长趋势，保守估计 |
    | 通胀率 | 1.0% | 名义折现率 = 实际折现率 + 通胀率 |
    | 年折旧率 | 1.0% | 参考住宅设计使用年限 50 年（每年 2%），扣除维护翻新因素的净折旧 |
    | 终值人口比例 | 60% | 基于中国人口结构预测：30 年后老龄化加剧，购房需求减少，残值缩水 40% |
    | 持有期 | 30 年 | 中国住宅产权 70 年，个人平均换房周期约 10-15 年，取 30 年作为长期持有参考 |
    | 首付比例 | 20% | 中国首套房最低首付比例 |
    | 贷款利率 | 2.6% | 参考 2025-2026 年 LPR 及公积金贷款利率 |
    | 贷款年限 | 30 年 | 最长期限 |
    """)

with st.expander("📋 估值区间说明"):
    st.markdown("""
    **公允价值 vs 市场售价的价差解读：**

    - **公允价值 > 售价**（价差为正）：房产的居住价值高于买入成本，从自住角度看值得购买
    - **公允价值 < 售价**（价差为负）：溢价部分反映地段、学区、供需等市场因素。溢价率在 10-20% 以内通常属于正常范围

    **敏感性分析的用途：**
    折现率和增长率是两个最敏感的参数。矩阵表格展示不同假设组合下的 NPV 变化，帮助你判断：
    - 你的判断是否偏离基准参数
    - 即使在乐观/悲观假设下，结论是否一致
    """)

