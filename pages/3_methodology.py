# 提前还贷
# ============================================================
st.subheader("四、提前还贷分析模型")

with st.expander("📘 模型原理", expanded=True):
    st.markdown("""
    提前还贷分析基于**等额本息还款公式**，模拟提前还贷后两种常见选择：

    - **方案A（缩短年限）**：月供不变，减少还款期数，节省总利息
    - **方案B（减少月供）**：年限不变，降低月供金额，释放每月现金流

    同时对比**提前还贷 vs 理财投资**：提前还贷的等效年化收益率就是贷款利率，属于确定收益；理财投资有市场风险。
    """)

with st.expander("📐 核心公式"):
    st.markdown("#### 等额本息月供")
    st.latex(r"""
    M = P \times \frac{i(1 + i)^N}{(1 + i)^N - 1}
    """)
    st.markdown("""
    **方案A（缩短年限）**：月供 M 不变，用提前还款后的剩余本金重新计算剩余期数 N'。

    **方案B（减少月供）**：剩余期数 N 不变，用提前还款后的剩余本金重新计算新月供 M'。
    """)

